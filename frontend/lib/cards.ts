export function getCardImageUrl(cardName: string): string {
  const number = cardNameToNumber[cardName];
  if (number === undefined) {
    return '/cards/placeholder.jpg';
  }
  return `https://ai-arcana.ru/cards/RWS_${String(number).padStart(5, '0')}.jpg`;
}

export function getCardNumber(cardName: string): number {
  return cardNameToNumber[cardName] ?? -1;
}
